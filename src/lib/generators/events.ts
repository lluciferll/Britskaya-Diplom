const TIME: TimeOfDay[] = ["утро", "день", "вечер", "ночь"];
const DANGER: Danger[] = ["мирно", "напряжённо", "опасно", "смертельно"];

export function generateEvent(opts: {
  seed?: number;
  context?: EventContext;
  time?: TimeOfDay;
  danger?: Danger;
}): RandomEventPack {
  const seed = typeof opts.seed === "number" ? (opts.seed >>> 0) : (Date.now() ^ (Math.floor(Math.random() * 1e9) >>> 0));
  const rng = mulberry32(seed);
  const ctx = opts.context ?? pick(rng, Object.keys(TABLES) as EventContext[]);
  const row = pick(rng, TABLES[ctx]);
  const timeLabel = opts.time ?? pick(rng, TIME);
  const dangerLabel = opts.danger ?? pick(rng, DANGER);

  let situation = row.situation;
  let twist = row.twist;
  let sensory = row.sensory;

  const dangerFlavor =
    dangerLabel === "смертельно"
      ? " Напряжение такое, что любая ошибка съедает ресурсы и репутацию."
      : dangerLabel === "опасно"
        ? " Возможен бой или жёсткая социальная цена."
        : dangerLabel === "напряжённо"
          ? " Можно решить умом, если не топором."
          : " Подходит как мягкая вставка в день.";

  const timeFlavor =
    timeLabel === "ночь"
      ? " Тени длиннее, слухи громче."
      : timeLabel === "утро"
        ? " Город просыпается: удобно для сделок и шантажа."
        : "";

  situation = `${situation}${timeFlavor}`;
  twist = `${twist}${dangerFlavor}`;

  return {
    seed,
    contextLabel: CONTEXT_LABELS[ctx],
    timeLabel,
    dangerLabel,
    situation,
    twist,
    sensory,
  };
}
