import type { ReferenceEntry } from "./types";

function spell(
  key: string,
  nameRu: string,
  nameEn: string,
  level: string,
  summary: string,
  body: string,
  tags: string[] = [],
): ReferenceEntry {
  return {
    key,
    category: "spells",
    nameRu,
    nameEn,
    subtitle: level,
    summary,
    body,
    tags: [nameEn.toLowerCase(), nameRu.toLowerCase(), ...tags],
  };
}

